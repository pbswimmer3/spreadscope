#!/bin/bash
# SpreadScope — One-Shot Deploy Script
# Usage: sudo bash deploy.sh
set -e

PROJECT_DIR="$(cd "$(dirname "$0")" && pwd)"
DB_PASSWORD="spreadscope_$(head -c 12 /dev/urandom | base64 | tr -dc 'a-zA-Z0-9' | head -c 16)"
DB_NAME="spreadscope_db"
DB_USER="spreadscope"
VENV_DIR="$PROJECT_DIR/.venv"
CONFIG_FILE="$PROJECT_DIR/config/config.yaml"
ACTUAL_USER="${SUDO_USER:-$(whoami)}"

echo "============================================================"
echo " SpreadScope — Deploy"
echo "============================================================"
echo "  Project: $PROJECT_DIR"
echo "  User:    $ACTUAL_USER"
echo ""

# ---- 1. Python virtual environment & dependencies ----
echo "[1/5] Setting up Python environment..."
if [ ! -d "$VENV_DIR" ]; then
    sudo -u "$ACTUAL_USER" python3 -m venv "$VENV_DIR"
fi
sudo -u "$ACTUAL_USER" "$VENV_DIR/bin/pip" install --quiet --upgrade pip
sudo -u "$ACTUAL_USER" "$VENV_DIR/bin/pip" install --quiet -r "$PROJECT_DIR/requirements.txt"
echo "  Done — packages installed in $VENV_DIR"

# ---- 2. Ensure TimescaleDB is loaded in PostgreSQL ----
echo "[2/5] Configuring PostgreSQL + TimescaleDB..."
PG_CONF=$(find /etc/postgresql -name postgresql.conf 2>/dev/null | head -1)
if [ -n "$PG_CONF" ]; then
    if ! grep -q "timescaledb" "$PG_CONF" 2>/dev/null; then
        echo "shared_preload_libraries = 'timescaledb'" >> "$PG_CONF"
        systemctl restart postgresql
        echo "  Added timescaledb to shared_preload_libraries and restarted PostgreSQL"
    else
        echo "  TimescaleDB already configured"
    fi
fi

# ---- 3. Create database user and database ----
echo "[3/5] Creating database..."

# Check if user already exists
if sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='$DB_USER'" | grep -q 1; then
    echo "  User '$DB_USER' already exists"
    # Reset the password to our generated one
    sudo -u postgres psql -c "ALTER USER $DB_USER WITH PASSWORD '$DB_PASSWORD';"
else
    sudo -u postgres psql -c "CREATE USER $DB_USER WITH PASSWORD '$DB_PASSWORD';"
    echo "  Created user '$DB_USER'"
fi

# Check if database already exists
if sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='$DB_NAME'" | grep -q 1; then
    echo "  Database '$DB_NAME' already exists — terminating connections and recreating"
    sudo -u postgres psql -c "SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = '$DB_NAME' AND pid <> pg_backend_pid();" > /dev/null 2>&1
    sleep 1
    sudo -u postgres psql -c "DROP DATABASE $DB_NAME;"
fi

sudo -u postgres psql -c "CREATE DATABASE $DB_NAME OWNER $DB_USER;"
sudo -u postgres psql -c "GRANT ALL PRIVILEGES ON DATABASE $DB_NAME TO $DB_USER;"
echo "  Created database '$DB_NAME'"

# Enable TimescaleDB extension
sudo -u postgres psql -d "$DB_NAME" -c "CREATE EXTENSION IF NOT EXISTS timescaledb CASCADE;"
echo "  TimescaleDB extension enabled"

# ---- 4. Run schema and seed data ----
echo "[4/5] Loading schema and seed data..."
cat "$PROJECT_DIR/schema.sql" | sudo -u postgres psql -d "$DB_NAME"
echo "  Schema loaded"

# Grant permissions on all tables to the spreadscope user
sudo -u postgres psql -d "$DB_NAME" -c "
    GRANT ALL ON ALL TABLES IN SCHEMA public TO $DB_USER;
    GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO $DB_USER;
    GRANT ALL ON SCHEMA public TO $DB_USER;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO $DB_USER;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO $DB_USER;
"

# Load seed data
sudo -u postgres psql -d "$DB_NAME" << 'SEEDEOF'
INSERT INTO venue_config (venue, display_name, venue_type, api_base_url, polling_interval_seconds, is_enabled, supports_assets) VALUES
('coinbase_spot', 'Coinbase Spot', 'spot', 'https://api.coinbase.com', 30, true, '{"BTC","ETH"}'),
('hyperliquid_perps', 'Hyperliquid Perps', 'perps', 'https://api.hyperliquid.xyz', 15, true, '{"BTC","ETH"}'),
('synthetix', 'Synthetix/Pyth Oracle', 'synthetic', 'https://hermes.pyth.network', 30, false, '{"BTC","ETH"}'),
('dydx', 'dYdX', 'perps', 'https://indexer.dydx.trade/v4', 30, false, '{"BTC","ETH"}')
ON CONFLICT (venue) DO NOTHING;

INSERT INTO tracked_pairs (asset, real_venue, synthetic_venue, threshold_pct, is_enabled) VALUES
('BTC', 'coinbase_spot', 'hyperliquid_perps', 0.05, true),
('ETH', 'coinbase_spot', 'hyperliquid_perps', 0.05, true)
ON CONFLICT (asset, real_venue, synthetic_venue) DO NOTHING;
SEEDEOF
echo "  Seed data loaded"

# ---- 5. Write config.yaml ----
echo "[5/5] Writing config file..."
mkdir -p "$(dirname "$CONFIG_FILE")"
cat > "$CONFIG_FILE" << CFGEOF
# SpreadScope Configuration — auto-generated by deploy.sh

database:
  host: localhost
  port: 5432
  name: $DB_NAME
  user: $DB_USER
  password: $DB_PASSWORD

venues:
  coinbase_spot:
    base_url: https://api.coinbase.com
    polling_interval: 30
    enabled: true

  hyperliquid:
    base_url: https://api.hyperliquid.xyz
    polling_interval: 15
    enabled: true

  synthetix:
    base_url: https://hermes.pyth.network
    polling_interval: 30
    enabled: false

  dydx:
    base_url: https://indexer.dydx.trade/v4
    polling_interval: 30
    enabled: false

assets:
  - BTC
  - ETH

thresholds:
  default_pct: 0.05
  staleness_max_seconds: 120

portfolio:
  capital_usd: 5000
  max_position_pct: 50
  min_position_usd: 100
  fee_per_trade_pct: 0.06

carry:
  min_annualized_rate_pct: 10.0
  min_funding_rate_pct: 0.01
  confirmation_periods: 3
  max_entry_spread_pct: 0.15
  exit_funding_rate_pct: 0.005
  spot_venues:
    - coinbase_spot
  perp_venues:
    - hyperliquid_perps

dashboard:
  host: 0.0.0.0
  port: 8050
  debug: false

logging:
  level: INFO
CFGEOF

chown "$ACTUAL_USER:$ACTUAL_USER" "$CONFIG_FILE"
echo "  Config written to $CONFIG_FILE"

echo ""
echo "============================================================"
echo " Deploy complete!"
echo "============================================================"
echo ""
echo "  DB password: $DB_PASSWORD"
echo "  Config:      $CONFIG_FILE"
echo "  Venv:        $VENV_DIR"
echo ""
echo "  To run manually:"
echo "    cd $PROJECT_DIR"
echo "    .venv/bin/python run_ingestion.py &"
echo "    .venv/bin/python run_calculator.py &"
echo "    .venv/bin/python run_dashboard.py"
echo ""
